#!/usr/bin/env python3
"""Generate protocol facts from pymavlink's ardupilotmega XML-derived dialect.
Maintainer-only dependency: pymavlink==2.4.50. No pymavlink needed on the sensor.
"""
from pathlib import Path
import importlib.metadata
from pymavlink.dialects.v20 import ardupilotmega as v2
from pymavlink.dialects.v10 import ardupilotmega as v1
version=importlib.metadata.version('pymavlink')
lines=[f'# Generated by tools/generate_mavlink_metadata.py; pymavlink {version}.',
 '# Protocol metadata from https://github.com/ArduPilot/pymavlink and MAVLink XML definitions.',
 '# CRC_EXTRA values are message-specific; they must not be omitted.',
 'module DroneMAVLink;', 'export {',
 '    type Message: record { crc: count; v1_length: count; name: string; };',
 '    const messages: table[count] of Message = {']
for i,c in sorted(v2.mavlink_map.items()):
 length=v1.mavlink_map[i].unpacker.size if i in v1.mavlink_map else 0
 lines.append(f'        [{i}] = [$crc={c.crc_extra}, $v1_length={length}, $name="{c.msgname}"],')
lines+=['    };','}']
Path(__file__).resolve().parents[1].joinpath('scripts/mavlink-metadata.zeek').write_text('\n'.join(lines)+'\n')
